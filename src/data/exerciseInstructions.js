export const getExerciseInstructions = (exerciseName) => {
  const safeName = String(exerciseName || '').trim() || 'Exercício personalizado';
  const normalizedName = normalizeExerciseSearch(safeName);
  const catalogGuide = NORMALIZED_CATALOG.get(normalizedName);
  if (catalogGuide) return catalogGuide;

  const alias = ALIAS_RULES.find(([pattern]) => pattern.test(normalizedName));
  const aliasedGuide = alias ? getLibraryGuide(alias[1]) : null;
  return Object.freeze({
    exerciseName: safeName,
    category: alias ? 'Variação reconhecida' : 'Exercício personalizado',
    source: alias ? 'variation' : 'fallback',
    ...(aliasedGuide || FALLBACK_GUIDE),
  });
};
